/**
 * One-off: give every existing article its CJK-segmented index columns.
 *
 *   node scripts/backfill-search-index.mjs            # dry run, prints the plan
 *   node scripts/backfill-search-index.mjs --apply    # writes a .sql, applies it, deletes it
 *
 * Why a script and not part of the migration
 * ------------------------------------------
 * Segmentation is `segmentCjk` from src/lib/cjk.ts — application code. The only way to
 * express it in SQL is a recursive CTE that splits a 9kB body into ~9000 rows, inside a
 * trigger, on every insert and update, on D1. So migration 0007 creates the columns and
 * the triggers and leaves the existing rows alone, and this fills them in.
 *
 * It writes the `fts_*` twins and nothing else: the `articles_fts_update` trigger from
 * 0007 fires on the UPDATE and re-indexes the row as a side effect, so the FTS table is
 * never touched directly and there is no second path that could disagree with the one
 * the running application uses.
 *
 * `segmentCjk` is imported, not copied. A copy in a script that runs against production
 * is a copy that eventually disagrees with the module the Worker imports, and the
 * symptom is an index nobody can search with nothing reporting why.
 *
 * Rows already holding a segmented `fts_content` are skipped, so it is safe to re-run —
 * which is the point, since it runs against production and a partial failure should be
 * resumable rather than restarted.
 */
import { spawnSync } from 'node:child_process';
import { readFileSync, unlinkSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { segmentCjk } from '../src/lib/cjk.ts';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const APPLY = process.argv.includes('--apply');
const DB = 'x-article-hub';

function sh(command) {
  const result = spawnSync('sh', ['-c', command], { encoding: 'utf8', maxBuffer: 256 * 1024 * 1024 });
  if (result.status !== 0) throw new Error(`${command}\n${result.stderr}`);
  return result.stdout;
}

/** `wrangler d1 execute --json` prints an array of result sets, one per statement. */
const query = (sql) =>
  JSON.parse(sh(`npx wrangler d1 execute ${DB} --remote --json --command ${JSON.stringify(sql)}`))[0].results;

/** SQLite single-quoted literals: double the quote, nothing else. */
const literal = (value) => `'${String(value).replace(/'/g, "''")}'`;

// The work set is "rows whose `fts_title` twin is still null". `fts_title` is the right
// probe because only this script and the crawl/parse writers set it, and a row that has
// been through either is already indexed; `fts_content` cannot be used, because
// migration 0007 renamed `content_text` in place, so a parsed row arrives here holding
// its raw body and still needs segmenting.
const rows = query(
  'SELECT id, title, excerpt, author_name, author_username, fts_content, fts_tags, fts_title FROM articles WHERE fts_title IS NULL',
);

console.log(`${rows.length} article(s) still to segment`);

if (!APPLY || rows.length === 0) {
  for (const row of rows.slice(0, 3)) {
    console.log(`  ${row.id}  fts_title=${row.fts_title === null ? 'null' : 'set'}  ${row.title ?? ''}`);
  }
  console.log(APPLY ? 'nothing to do' : 'dry run — pass --apply');
  process.exit(0);
}

// Sanity: the segmenter must be idempotent, or a re-run would double-space the index.
for (const row of rows) {
  const once = segmentCjk(row.fts_content ?? '');
  if (segmentCjk(once) !== once) throw new Error(`segmentCjk is not idempotent on ${row.id}`);
}

// No BEGIN/COMMIT. D1 rejects explicit SQL transactions outright — it requires
// `state.storage.transaction()`, which is a JavaScript API and unavailable to a
// `--file` apply. So the statements are not atomic as a group, which is exactly why
// the resumability above matters: a partial apply leaves some rows segmented and some
// not, and re-running finishes the rest. The post-apply count below is what tells you
// whether that happened.
const statements = ['-- generated by scripts/backfill-search-index.mjs — safe to delete once applied'];
for (const row of rows) {
  statements.push(
    `UPDATE articles SET
       fts_content = ${literal(segmentCjk(row.fts_content ?? ''))},
       fts_tags = ${literal(segmentCjk(row.fts_tags ?? ''))},
       fts_title = ${literal(segmentCjk(row.title ?? ''))},
       fts_excerpt = ${literal(segmentCjk(row.excerpt ?? ''))},
       fts_author_name = ${literal(segmentCjk(row.author_name ?? ''))},
       fts_author_username = ${literal(segmentCjk(row.author_username ?? ''))}
     WHERE id = ${literal(row.id)};`,
  );
}

const file = resolve(ROOT, 'backfill-search-index.sql');
writeFileSync(file, `${statements.join('\n')}\n`, 'utf8');
console.log(`wrote ${rows.length} statements to ${file}`);

try {
  sh(`npx wrangler d1 execute ${DB} --remote --file ${JSON.stringify(file)}`);
  unlinkSync(file);
} catch (error) {
  console.error(`apply failed — ${file} left in place so the statements can be read`);
  throw error;
}

const left = query('SELECT COUNT(*) AS n FROM articles WHERE fts_title IS NULL')[0].n;
console.log(left === 0 ? 'applied — every row segmented' : `applied — ${left} row(s) still left, re-run to finish`);